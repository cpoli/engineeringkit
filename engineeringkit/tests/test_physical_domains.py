@pytest.mark.parametrize("domain,model,args", CASES, ids=[f"{d}.{f}" for d, f, _ in CASES])
def test_invalid_physical_input(domain, model, args):
    fn = getattr(importlib.import_module("engineeringkit." + domain), model)
    with pytest.raises(ValueError):
        fn(*args)


@pytest.mark.parametrize("bad", [np.nan, np.inf, -np.inf])
@pytest.mark.parametrize(
    "domain,model,args",
    [
        ("thermodynamics", "ideal_gas_pressure", [1, 300, 1]),
        ("fluid_engineering", "reynolds_number", [1000, 1, 0.1, 0.001]),
        ("aerodynamics", "normal_shock_mach2", [2]),
        ("materials", "shear_modulus", [200e9, 0.3]),
        ("reliability", "exponential_reliability", [1, 0.1]),
        ("communications", "shannon_capacity", [1e6, 10]),
        ("heat_transfer", "fourier_heat_rate", [10, 1, 20, 0.1]),
        ("electrical_engineering", "resonance_frequency", [1, 1]),
        ("structural_engineering", "euler_buckling_load", [200e9, 1e-5, 1]),
        ("mechanical_engineering", "kinetic_energy", [1, 1]),
    ],
)
def test_nonfinite_values_never_silently_propagate(domain, model, args, bad):
    fn = getattr(importlib.import_module("engineeringkit." + domain), model)
    for i in range(len(args)):
        values = args.copy()
        values[i] = bad
        with pytest.raises(ValueError):
            fn(*values)
